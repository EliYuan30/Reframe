class ImageInterpreter:
    """Typed AST evaluator, not Python execution or a Python security sandbox."""
    MAX_IMAGE_PIXELS = 16_000_000
    MAX_ALLOCATED_PIXELS = 32_000_000
    IMPORTS = {"PIL": {"Image": "Image"}, "matplotlib": {"pyplot": "plt"},
               "matplotlib.pyplot": {}, "numpy": {}, "cv2": {}, "math": {"floor": "floor", "ceil": "ceil", "sqrt": "sqrt"},
               "IPython.display": {"display": "display"}}

    def __init__(self, image: Image.Image, protocol: str):
        self.protocol = protocol
        original = Frame(image, (0., 0., float(image.width), float(image.height)))
        self.original = original
        self.env = {"image": original, "image_1": original, "images": [original],
                    **{name: Symbol(name) for name in ("Image", "plt", "np", "cv2", "math", "display")}}
        self.allocated = 0

    @staticmethod
    def fail(message):
        raise UnsupportedOperation(message)

    def number(self, value):
        if type(value) not in (int, float) or not math.isfinite(value) or abs(value) > 1e9:
            self.fail("Expected bounded finite number")
        return value

    def scalar(self, value):
        if value is None or type(value) in (int, float, str, bool):
            return str(value)
        self.fail("Only scalar stdout is supported")

    def allocate(self, frame, size, box=None, array=None, bgr=None):
        if not isinstance(size, (tuple, list)) or len(size) != 2 or any(type(v) is not int or v <= 0 for v in size):
            self.fail("Image dimensions must be positive integers")
        pixels = size[0] * size[1]
        if pixels > self.MAX_IMAGE_PIXELS or self.spent + pixels > self.MAX_ALLOCATED_PIXELS:
            self.fail("Image memory limit exceeded")
        self.spent += pixels
        return Frame(frame.image, box or frame.box, frame.array if array is None else array,
                     frame.bgr if bgr is None else bgr)

    def crop(self, frame, box):
        if not isinstance(frame, Frame) or not isinstance(box, (tuple, list)) or len(box) != 4:
            self.fail("crop requires image and four coordinates")
        values = [self.number(v) for v in box]
        x1, y1, x2, y2 = [round(v) for v in values]
        if not (0 <= x1 < x2 <= frame.image.width and 0 <= y1 < y2 <= frame.image.height):
            self.fail("Crop must be nonempty and inside current image")
        a, b, c, d = frame.box
        source = (a + x1 / frame.image.width * (c-a), b + y1 / frame.image.height * (d-b),
                  a + x2 / frame.image.width * (c-a), b + y2 / frame.image.height * (d-b))
        out = self.allocate(frame, (x2-x1, y2-y1), box=source)
        return Frame(frame.image.crop((x1, y1, x2, y2)), out.box, out.array, out.bgr)

    def emit(self, value):
        if not isinstance(value, Frame):
            self.fail("display requires an in-memory image")
        if len(self.outputs) >= 3:
            self.fail("At most three image outputs per operation")
        if value.array and value.bgr:
            self.allocate(value, value.image.size)
            self.allocate(value, value.image.size)
            r, g, b = value.image.split()
            value = Frame(Image.merge("RGB", (b, g, r)), value.box)
        self.outputs.append(value)

    def run(self, code: str) -> CodeResult:
        if len(code) > 16384:
            self.fail("Code length limit exceeded")
        try:
            tree = ast.parse(code)
        except (SyntaxError, RecursionError, ValueError) as exc:
            raise UnsupportedOperation("Malformed or excessive code") from exc
        pending = [(tree, 0)]
        nodes = 0
        while pending:
            node, depth = pending.pop()
            nodes += 1
            if nodes > 512 or depth > 32:
                self.fail("AST resource limit exceeded")
            pending.extend((child, depth+1) for child in ast.iter_child_nodes(node))
        if len(tree.body) > 64:
            self.fail("Statement limit exceeded")
        self.work = dict(self.env)
        self.outputs, self.stdout, self.saved, self.pending_image = [], [], {}, None
        self.spent, self.steps = self.allocated, 0
        try:
            if self.protocol == "thyme":
                self.virtual_dirs, self.statements, self.loop_items = set(), 0, 0
                self.thyme_block(tree.body, top=True)
            else:
                for index, stmt in enumerate(tree.body):
                    if isinstance(stmt, (ast.Import, ast.ImportFrom)):
                        self.bind_import(stmt)
                    elif isinstance(stmt, ast.Assign) and len(stmt.targets) == 1:
                        self.assign(stmt.targets[0], self.expr(stmt.value))
                    elif isinstance(stmt, ast.Expr):
                        value = self.expr(stmt.value)
                        if index == len(tree.body)-1 and isinstance(value, Frame):
                            self.emit(value)
                    else:
                        self.fail(f"Unsupported statement: {type(stmt).__name__}")
        except UnsupportedOperation:
            raise
        except (ValueError, TypeError, ZeroDivisionError, IndexError, KeyError, OverflowError) as exc:
            raise UnsupportedOperation(f"Invalid bounded image code: {exc}") from exc
        self.env, self.allocated = self.work, self.spent
        return CodeResult(self.outputs, "".join(self.stdout))

    def bind_import(self, stmt):
        if self.protocol == "thyme":
            return self.bind_thyme_import(stmt)
        return self.bind_native_import(stmt)

    def bind_native_import(self, stmt):
        if isinstance(stmt, ast.Import):
            for entry in stmt.names:
                symbols = {"numpy": "np", "cv2": "cv2", "math": "math", "matplotlib.pyplot": "plt"}
                if entry.name not in symbols:
                    self.fail(f"Unsupported import: {entry.name}")
                name = entry.asname or entry.name.split('.')[0]
                self.assign(ast.Name(id=name), Symbol(symbols[entry.name] if entry.asname or '.' not in entry.name else "matplotlib"))
        else:
            allowed = self.IMPORTS.get(stmt.module) if stmt.level == 0 else None
            for entry in stmt.names:
                if allowed is None or entry.name not in allowed:
                    self.fail("Unsupported from-import")
                self.assign(ast.Name(id=entry.asname or entry.name), Symbol(allowed[entry.name]))

    def assign(self, target, value):
        if isinstance(target, ast.Name) and not target.id.startswith('_'):
            if len(self.work) >= 96 and target.id not in self.work:
                self.fail("Variable limit exceeded")
            self.work[target.id] = value
        elif isinstance(target, (ast.Tuple, ast.List)) and isinstance(value, (tuple, list)) and len(target.elts) == len(value):
            for part, item in zip(target.elts, value):
                self.assign(part, item)
        else:
            self.fail("Only bounded variable assignment is supported")

    def expr(self, node):
        self.steps += 1
        if self.steps > 2048:
            self.fail("Evaluation step limit exceeded")
        if isinstance(node, ast.Constant):
            value = node.value
            if type(value) in (int, float):
                return self.number(value)
            if value is None or type(value) is bool or (type(value) is str and len(value) <= 4096):
                return value
        elif isinstance(node, ast.Name) and not node.id.startswith('_'):
            if node.id in self.work:
                return self.work[node.id]
            if node.id in {"min", "max", "abs", "int", "float", "round", "len", "print"}:
                return Symbol(node.id)
            if self.protocol == "thyme" and node.id in {"str", "range"}:
                return Symbol(node.id)
        elif isinstance(node, (ast.Tuple, ast.List)) and len(node.elts) <= 32:
            values = [self.expr(item) for item in node.elts]
            return tuple(values) if isinstance(node, ast.Tuple) else values
        elif isinstance(node, ast.UnaryOp) and isinstance(node.op, (ast.UAdd, ast.USub)):
            value = self.number(self.expr(node.operand))
            return self.number(-value if isinstance(node.op, ast.USub) else value)
        elif isinstance(node, ast.BinOp):
            if self.protocol == "thyme":
                return self.thyme_binop(node.op, self.expr(node.left), self.expr(node.right))
            a, b = self.number(self.expr(node.left)), self.number(self.expr(node.right))
            if isinstance(node.op, ast.Add): value = a+b
            elif isinstance(node.op, ast.Sub): value = a-b
            elif isinstance(node.op, ast.Mult): value = a*b
            elif isinstance(node.op, ast.Div): value = a/b
            elif isinstance(node.op, ast.FloorDiv): value = a//b
            else: self.fail("Unsupported arithmetic")
            return self.number(value)
        elif isinstance(node, ast.Attribute):
            if node.attr.startswith('_'):
                self.fail("Reflection is forbidden")
            value = self.expr(node.value)
            if isinstance(value, Frame):
                if node.attr == "size": return value.image.size
                if node.attr == "width": return value.image.width
                if node.attr == "height": return value.image.height
                if node.attr == "shape" and value.array: return (value.image.height, value.image.width, 3)
            if isinstance(value, Symbol):
                name = value.name + "." + node.attr
                constants = {"Image.Resampling.LANCZOS": 1, "Image.LANCZOS": 1, "Image.BICUBIC": 3,
                             "Image.Resampling.BICUBIC": 3, "Image.BILINEAR": 2,
                             "cv2.COLOR_BGR2RGB": "BGR2RGB", "cv2.COLOR_RGB2BGR": "RGB2BGR",
                             "cv2.INTER_CUBIC": 3, "cv2.INTER_LINEAR": 2}
                if name in constants: return constants[name]
                if name in {"Image.Resampling", "matplotlib.pyplot"}: return Symbol("plt" if name == "matplotlib.pyplot" else name)
                if self.protocol == "thyme":
                    if name in THYME_CONSTANTS: return THYME_CONSTANTS[name]
                    if name == "os.path" or name == "np.random": return Symbol(name)
            if self.protocol == "thyme" and isinstance(value, VirtualUUID) and node.attr == "hex":
                return value.text.replace("-", "")
            self.fail("Unsupported attribute")
        elif isinstance(node, ast.Subscript):
            value = self.expr(node.value)
            if isinstance(value, Frame) and value.array:
                parts = node.slice.elts if isinstance(node.slice, ast.Tuple) else []
                if len(parts) not in (2, 3) or any(not isinstance(item, ast.Slice) for item in parts):
                    self.fail("Only ndarray rectangular slice crops are supported")
                bounds = []
                for part, limit in zip(parts[:2], (value.image.height, value.image.width)):
                    if part.step is not None and self.expr(part.step) != 1: self.fail("Unsupported slice step")
                    bounds.append((0 if part.lower is None else self.expr(part.lower), limit if part.upper is None else self.expr(part.upper)))
                out = self.crop(value, (bounds[1][0], bounds[0][0], bounds[1][1], bounds[0][1]))
                if len(parts) == 3:
                    part = parts[2]
                    if part.lower is not None or part.upper is not None: self.fail("Unsupported channel slice")
                    if part.step is not None:
                        if self.expr(part.step) != -1: self.fail("Unsupported channel step")
                        out = Frame(out.image, out.box, True, not out.bgr)
                return out
            text = self.protocol == "thyme" and type(value) is str
            if (isinstance(value, (tuple, list)) or text) and isinstance(node.slice, ast.Slice):
                parts = [self.expr(part) if part is not None else None
                         for part in (node.slice.lower, node.slice.upper, node.slice.step)]
                if any(part is not None and type(part) is not int for part in parts):
                    self.fail("Sequence slice indices must be integers")
                return value[slice(*parts)]
            index = self.expr(node.slice)
            if (isinstance(value, (tuple, list)) or text) and type(index) is int:
                return value[index]
            self.fail("Unsupported subscript")
        elif isinstance(node, ast.Call):
            if any(isinstance(arg, ast.Starred) for arg in node.args) or any(kw.arg is None for kw in node.keywords):
                self.fail("Argument expansion is forbidden")
            args = [self.expr(arg) for arg in node.args]
            kwargs = {kw.arg: self.expr(kw.value) for kw in node.keywords}
            if isinstance(node.func, ast.Attribute):
                return self.call(self.expr(node.func.value), node.func.attr, args, kwargs)
            symbol = self.expr(node.func)
            if isinstance(symbol, Symbol):
                return self.call(symbol, "", args, kwargs)
        if self.protocol == "thyme":
            return self.thyme_expr(node)
        self.fail(f"Unsupported expression: {type(node).__name__}")

    def call(self, receiver, method, args, kwargs):
        if method.startswith('_'):
            self.fail("Reflection is forbidden")
        if isinstance(receiver, Frame):
            if method == "crop" and len(args) == 1 and not kwargs: return self.crop(receiver, args[0])
            if method == "resize" and 1 <= len(args) <= 2 and not set(kwargs)-{"resample"}:
                out = self.allocate(receiver, args[0])
                resample = args[1] if len(args) == 2 else kwargs.get("resample", 3)
                if type(resample) is not int or resample not in (0, 1, 2, 3): self.fail("Unsupported resampling")
                return Frame(receiver.image.resize(tuple(args[0]), resample=resample), out.box, out.array, out.bgr)
            if method == "convert" and args == ["RGB"] and not kwargs:
                return Frame(receiver.image, receiver.box)
            if method == "save" and self.protocol == "thyme" and 1 <= len(args) <= 2 and not set(kwargs)-{"format", "quality"}:
                if any(type(value) is not str for value in args[1:]) or type(kwargs.get("format", "")) is not str:
                    self.fail("Invalid save format")
                self.thyme_store(args[0], receiver)
                return None
            if self.protocol == "thyme":
                result = self.thyme_frame_method(receiver, method, args, kwargs)
                if result is not _UNHANDLED:
                    return result
            self.fail(f"Unsupported image method: {method}")
        if self.protocol == "thyme" and not isinstance(receiver, Symbol):
            return self.thyme_value_method(receiver, method, args, kwargs)
        if not isinstance(receiver, Symbol): self.fail("Arbitrary calls are forbidden")
        name = receiver.name + ("." + method if method else "")
        if self.protocol == "thyme":
            result = self.thyme_symbol_call(name, args, kwargs)
            if result is not _UNHANDLED:
                return result
        if name in {"Image.open", "cv2.imread"} and len(args) == 1 and not kwargs:
            if self.protocol != "thyme" or args[0] != ORIGINAL_ALIAS: self.fail("Only the original in-memory alias can be opened")
            return Frame(self.original.image, self.original.box, name == "cv2.imread", name == "cv2.imread")
        if name in {"np.array", "np.asarray", "Image.fromarray"} and len(args) == 1 and not kwargs and isinstance(args[0], Frame):
            value = args[0]
            if name == "Image.fromarray" and value.bgr:
                self.allocate(value, value.image.size)
                self.allocate(value, value.image.size)
                r, g, b = value.image.split()
                return Frame(Image.merge("RGB", (b, g, r)), value.box)
            return Frame(value.image, value.box, name != "Image.fromarray", value.bgr)
        if name == "cv2.cvtColor" and len(args) == 2 and not kwargs and isinstance(args[0], Frame) and args[1] in ("BGR2RGB", "RGB2BGR"):
            value = args[0]
            return Frame(value.image, value.box, True, not value.bgr)
        if name == "cv2.resize" and len(args) == 2 and not set(kwargs)-{"interpolation"}:
            return self.call(args[0], "resize", [args[1]], {"resample": kwargs.get("interpolation", 2)})
        if name == "display" and len(args) == 1 and not kwargs:
            self.emit(args[0]); return None
        if name == "plt.imshow" and len(args) == 1 and not set(kwargs)-{"cmap"} and isinstance(args[0], Frame):
            self.pending_image = args[0]; return None
        if name == "plt.show" and not args and not kwargs:
            if self.pending_image is not None:
                self.emit(self.pending_image); self.pending_image = None
            return None
        if name in {"plt.figure", "plt.axis", "plt.title", "plt.tight_layout", "plt.close"}:
            if len(args) > 1 or set(kwargs)-{"figsize"}: self.fail("Unsupported plot arguments")
            return None
        if name == "print" and not set(kwargs)-{"sep", "end"}:
            sep, end = kwargs.get("sep", " "), kwargs.get("end", "\n")
            if type(sep) is not str or type(end) is not str: self.fail("Invalid print separators")
            for value in args:
                if self.protocol == "thyme":
                    self.thyme_print_images(value)
                elif type(value) is str and value in self.saved: self.emit(self.saved[value])
            render = self.thyme_text if self.protocol == "thyme" else self.scalar
            text = sep.join(render(value) for value in args) + end
            if sum(map(len, self.stdout))+len(text) > 4096: self.fail("stdout limit exceeded")
            self.stdout.append(text); return None
        if kwargs: self.fail("Unsupported keyword arguments")
        if name == "len" and len(args) == 1 and isinstance(args[0], (str, list, tuple)): return len(args[0])
        if name in {"min", "max"}:
            values = args[0] if len(args) == 1 and isinstance(args[0], (list, tuple)) else args
            if not values: self.fail("Empty extrema")
            values = [self.number(value) for value in values]
            return min(values) if name == "min" else max(values)
        if name == "round" and 1 <= len(args) <= 2:
            if len(args) == 2 and (type(args[1]) is not int or abs(args[1]) > 8): self.fail("round precision limit")
            return self.number(round(self.number(args[0]), *args[1:]))
        functions = {"abs": abs, "int": int, "float": float, "math.floor": math.floor, "floor": math.floor,
                     "math.ceil": math.ceil, "ceil": math.ceil, "math.sqrt": math.sqrt, "sqrt": math.sqrt}
        if name in functions and len(args) == 1: return self.number(functions[name](self.number(args[0])))
        self.fail(f"Unsupported call: {name}")


    def thyme_block(self, body, top=False):
        for index, stmt in enumerate(body):
            self.statements += 1
            if self.statements > THYME_MAX_STATEMENTS:
                self.fail("Executed statement limit exceeded")
            if isinstance(stmt, (ast.Import, ast.ImportFrom)):
                self.bind_import(stmt)
            elif isinstance(stmt, ast.Assign):
                value = self.expr(stmt.value)
                for target in stmt.targets:
                    self.assign(target, value)
            elif isinstance(stmt, ast.AugAssign) and isinstance(stmt.target, ast.Name):
                current = self.expr(ast.Name(id=stmt.target.id, ctx=ast.Load()))
                self.assign(stmt.target, self.thyme_binop(stmt.op, current, self.expr(stmt.value)))
            elif isinstance(stmt, ast.Expr):
                value = self.expr(stmt.value)
                if top and index == len(body)-1 and isinstance(value, Frame):
                    self.emit(value)
            elif isinstance(stmt, ast.If):
                self.thyme_block(stmt.body if self.thyme_truth(self.expr(stmt.test)) else stmt.orelse)
            elif isinstance(stmt, ast.For) and not stmt.orelse:
                items = self.expr(stmt.iter)
                if not isinstance(items, (tuple, list, str)) or len(items) > THYME_MAX_LOOP_ITEMS:
                    self.fail(f"for loops need a sequence of <= {THYME_MAX_LOOP_ITEMS} items")
                self.loop_items += len(items)
                if self.loop_items > THYME_MAX_LOOP_TOTAL:
                    self.fail("Loop iteration limit exceeded")
                for item in list(items):
                    self.assign(stmt.target, item)
                    self.thyme_block(stmt.body)
            elif isinstance(stmt, ast.Pass):
                continue
            else:
                self.fail(f"Unsupported statement: {type(stmt).__name__}")

    def bind_thyme_import(self, stmt):
        for entry in stmt.names:
            if isinstance(stmt, ast.Import):
                if entry.name in THYME_IMPORTS:
                    head = entry.name.split('.')[0]
                    self.assign(ast.Name(id=entry.asname or head), Symbol(entry.name if entry.asname else head))
                    continue
                self.bind_native_import(ast.Import(names=[entry]))
            else:
                module = THYME_FROM_IMPORTS.get(stmt.module, {}) if stmt.level == 0 else {}
                if entry.name in module:
                    self.assign(ast.Name(id=entry.asname or entry.name), Symbol(module[entry.name]))
                    continue
                self.bind_native_import(ast.ImportFrom(module=stmt.module, names=[entry], level=stmt.level))

    def thyme_inputs(self) -> set[str]:
        return {ORIGINAL_ALIAS}

    def thyme_print_images(self, value):
        if type(value) is not str:
            return
        if value in self.saved:
            self.emit(self.saved[value])
            return
        found = []
        for path in self.saved:
            for match in re.finditer(r"(?<![^\s'\"])" + re.escape(path) + r"(?![^\s'\"])", value):
                found.append((match.start(), path))
                break
        for _, path in sorted(found):
            self.emit(self.saved[path])

    def thyme_str(self, value):
        if type(value) is not str or len(value) > THYME_MAX_TEXT:
            self.fail("Expected a bounded string")
        return value

    def thyme_text(self, value):
        if isinstance(value, VirtualUUID):
            return value.text
        if isinstance(value, (tuple, list)) and len(value) <= 32 and all(
                item is None or type(item) in (int, float, str, bool) for item in value):
            return self.thyme_str(str(value))
        return self.thyme_str(self.scalar(value))

    def thyme_truth(self, value):
        if value is None or type(value) in (int, float, str, bool, tuple, list):
            return bool(value)
        self.fail("Only scalar or sequence truth values are supported")

    def thyme_binop(self, op, a, b):
        if isinstance(op, ast.Add) and type(a) is str and type(b) is str:
            if len(a) + len(b) > THYME_MAX_TEXT: self.fail("String length limit exceeded")
            return a + b
        a, b = self.number(a), self.number(b)
        if isinstance(op, ast.Add): value = a+b
        elif isinstance(op, ast.Sub): value = a-b
        elif isinstance(op, ast.Mult): value = a*b
        elif isinstance(op, ast.Div): value = a/b
        elif isinstance(op, ast.FloorDiv): value = a//b
        elif isinstance(op, ast.Mod): value = a % b
        else: self.fail("Unsupported arithmetic")
        return self.number(value)

    def thyme_expr(self, node):
        if isinstance(node, ast.JoinedStr):
            parts = []
            for part in node.values:
                if isinstance(part, ast.Constant) and type(part.value) is str:
                    parts.append(part.value)
                    continue
                if not isinstance(part, ast.FormattedValue):
                    self.fail("Unsupported f-string part")
                value = self.expr(part.value)
                if isinstance(value, VirtualUUID):
                    value = value.text
                if value is not None and type(value) not in (int, float, str, bool):
                    self.fail("f-strings format scalars only")
                if part.conversion == ord('r'): value = repr(value)
                elif part.conversion in (ord('s'), ord('a')): value = str(value) if part.conversion == ord('s') else ascii(value)
                spec = ""
                if part.format_spec is not None:
                    pieces = part.format_spec.values if isinstance(part.format_spec, ast.JoinedStr) else []
                    if not all(isinstance(item, ast.Constant) and type(item.value) is str for item in pieces):
                        self.fail("Only literal f-string format specs are supported")
                    spec = "".join(item.value for item in pieces)
                    if not THYME_FORMAT_SPEC.match(spec):
                        self.fail("Unsupported f-string format spec")
                parts.append(format(value, spec))
                if sum(map(len, parts)) > THYME_MAX_TEXT:
                    self.fail("String length limit exceeded")
            return self.thyme_str("".join(parts))
        if isinstance(node, ast.UnaryOp) and isinstance(node.op, ast.Not):
            return not self.thyme_truth(self.expr(node.operand))
        if isinstance(node, ast.BoolOp):
            value = None
            for item in node.values:
                value = self.expr(item)
                truth = self.thyme_truth(value)
                if truth != isinstance(node.op, ast.And):
                    return value
            return value
        if isinstance(node, ast.IfExp):
            return self.expr(node.body if self.thyme_truth(self.expr(node.test)) else node.orelse)
        if isinstance(node, ast.Compare):
            left = self.expr(node.left)
            for op, right_node in zip(node.ops, node.comparators):
                right = self.expr(right_node)
                if not self.thyme_compare(op, left, right):
                    return False
                left = right
            return True
        self.fail(f"Unsupported expression: {type(node).__name__}")

    def thyme_compare(self, op, a, b):
        scalar = (int, float, str, bool)
        if isinstance(op, (ast.Is, ast.IsNot)):
            if b is not None: self.fail("Only `is None` comparisons are supported")
            return (a is None) == isinstance(op, ast.Is)
        if isinstance(op, (ast.In, ast.NotIn)):
            if type(b) is str and type(a) is str: found = a in b
            elif isinstance(b, (tuple, list)) and all(item is None or type(item) in scalar for item in b) and (a is None or type(a) in scalar):
                found = a in b
            else: self.fail("Unsupported membership test")
            return found == isinstance(op, ast.In)
        if (a is not None and type(a) not in scalar) or (b is not None and type(b) not in scalar):
            self.fail("Only scalar comparisons are supported")
        if isinstance(op, ast.Eq): return a == b
        if isinstance(op, ast.NotEq): return a != b
        if not ((type(a) is str and type(b) is str) or (type(a) in (int, float, bool) and type(b) in (int, float, bool))):
            self.fail("Ordering needs two numbers or two strings")
        if isinstance(op, ast.Lt): return a < b
        if isinstance(op, ast.LtE): return a <= b
        if isinstance(op, ast.Gt): return a > b
        if isinstance(op, ast.GtE): return a >= b
        self.fail("Unsupported comparison")

    def thyme_path(self, value):
        if type(value) is not str or not value or len(value) > THYME_MAX_PATH or "\x00" in value:
            self.fail("Expected a bounded virtual path string")
        return value

    def thyme_store(self, path, frame):
        path = self.thyme_path(path)
        if path not in RESULT_ALIASES:
            normal = posixpath.normpath(path)
            if (not normal.startswith(THYME_VIRTUAL_ROOT) or path.endswith("/") or ".." in path.split("/")
                    or normal in {posixpath.normpath(item) for item in self.thyme_inputs()}):
                self.fail(f"Only non-input virtual paths under {THYME_VIRTUAL_ROOT} are writable")
        if path not in self.saved and len(self.saved) >= THYME_MAX_SAVED:
            self.fail("Too many saved virtual images")
        self.saved[path] = frame

    def thyme_exists(self, path, kind="any"):
        normal = posixpath.normpath(self.thyme_path(path))
        files = {posixpath.normpath(item) for item in (*self.thyme_inputs(), *self.saved)}
        dirs = set()
        for item in (*files, *self.virtual_dirs):
            parent = item if item in self.virtual_dirs else posixpath.dirname(item)
            while parent and parent not in dirs:
                dirs.add(parent)
                parent = posixpath.dirname(parent) if parent != "/" else ""
        if kind == "file": return normal in files
        if kind == "dir": return normal in dirs
        return normal in files or normal in dirs

    def thyme_pixels(self, frame):
        if not isinstance(frame, Frame) or frame.array:
            self.fail("Expected a PIL image")
        return frame

    def thyme_frame_method(self, frame, method, args, kwargs):
        if method == "rotate" and len(args) == 1 and not set(kwargs)-{"expand", "resample"}:
            frame = self.thyme_pixels(frame)
            angle = self.number(args[0])
            expand, resample = kwargs.get("expand", False), kwargs.get("resample", 0)
            if type(expand) not in (bool, int) or abs(angle) > 3600 or resample not in (0, 2, 3):
                self.fail("Unsupported rotate arguments")
            width, height = frame.image.size
            if expand:
                radians = math.radians(angle)
                cos, sin = abs(math.cos(radians)), abs(math.sin(radians))
                width, height = math.ceil(width*cos + height*sin) + 1, math.ceil(width*sin + height*cos) + 1
            out = self.allocate(frame, (width, height))
            return Frame(frame.image.rotate(angle, expand=bool(expand), resample=resample), out.box)
        if method == "convert" and args == ["L"] and not kwargs:
            frame = self.thyme_pixels(frame)
            out = self.allocate(frame, frame.image.size)
            return Frame(frame.image.convert("L"), out.box)
        if method == "copy" and not args and not kwargs:
            out = self.allocate(frame, frame.image.size)
            return Frame(frame.image.copy(), out.box, out.array, out.bgr)
        return _UNHANDLED

    def thyme_value_method(self, receiver, method, args, kwargs):
        if isinstance(receiver, Enhancer) and method == "enhance" and len(args) == 1 and not kwargs:
            factor = self.number(args[0])
            if not 0 <= factor <= 16:
                self.fail("Enhancement factor must be within [0, 16]")
            out = self.allocate(receiver.frame, receiver.frame.image.size)
            return Frame(THYME_ENHANCERS[receiver.kind](receiver.frame.image).enhance(factor), out.box)
        if type(receiver) is str and not kwargs:
            receiver = self.thyme_str(receiver)
            if method in {"lower", "upper", "strip"} and not args:
                return getattr(receiver, method)()
            if method in {"startswith", "endswith"} and len(args) == 1:
                return getattr(receiver, method)(self.thyme_str(args[0]))
            if method in {"split", "rsplit"} and len(args) <= 2:
                sep = args[0] if args else None
                if sep is not None: self.thyme_str(sep)
                if len(args) == 2 and type(args[1]) is not int: self.fail("maxsplit must be an integer")
                return getattr(receiver, method)(*args)
            if method == "replace" and len(args) == 2:
                old, new = self.thyme_str(args[0]), self.thyme_str(args[1])
                if not old or len(receiver) + receiver.count(old) * max(0, len(new) - len(old)) > THYME_MAX_TEXT:
                    self.fail("Unsupported or oversized replace")
                return receiver.replace(old, new)
            if method == "join" and len(args) == 1 and isinstance(args[0], (tuple, list)):
                items = [self.thyme_str(item) for item in args[0]]
                if sum(map(len, items)) + len(receiver) * max(0, len(items) - 1) > THYME_MAX_TEXT:
                    self.fail("String length limit exceeded")
                return receiver.join(items)
        self.fail("Arbitrary calls are forbidden")

    def thyme_symbol_call(self, name, args, kwargs):
        if name.startswith("os.path."):
            function = name[len("os.path."):]
            if kwargs: self.fail("Unsupported keyword arguments")
            if function == "join" and 1 <= len(args) <= 32:
                value = posixpath.join(*[self.thyme_path(item) for item in args])
                return self.thyme_path(value)
            if function in {"basename", "dirname", "splitext", "split"} and len(args) == 1:
                return getattr(posixpath, function)(self.thyme_path(args[0]))
            if function in {"exists", "isfile", "isdir"} and len(args) == 1:
                return self.thyme_exists(args[0], {"exists": "any", "isfile": "file", "isdir": "dir"}[function])
            self.fail(f"Unsupported call: {name}")
        if name in {"os.makedirs", "os.mkdir"} and len(args) == 1 and not set(kwargs)-({"exist_ok"} if name == "os.makedirs" else set()):
            path = posixpath.normpath(self.thyme_path(args[0]))
            if type(kwargs.get("exist_ok", False)) is not bool: self.fail("exist_ok must be a bool")
            if not kwargs.get("exist_ok", False) and self.thyme_exists(path):
                self.fail(f"Virtual directory already exists: {path}")
            if len(self.virtual_dirs) >= 16: self.fail("Too many virtual directories")
            self.virtual_dirs.add(path)
            return None
        if name == "random.randint" and len(args) == 2 and not kwargs:
            if any(type(item) is not int for item in args) or args[0] > args[1]:
                self.fail("randint needs integer bounds a <= b")
            return self.number(args[0])
        if name == "np.random.randint" and 1 <= len(args) <= 2 and not kwargs:
            low, high = (0, args[0]) if len(args) == 1 else args
            if type(low) is not int or type(high) is not int or low >= high:
                self.fail("np.random.randint needs integer bounds low < high")
            return self.number(low)
        if name == "random.choice" and len(args) == 1 and not kwargs:
            if not isinstance(args[0], (tuple, list, str)) or not args[0]:
                self.fail("choice needs a non-empty sequence")
            return args[0][0]
        if name == "uuid.uuid4" and not args and not kwargs:
            return VirtualUUID()
        if name == "str" and len(args) <= 1 and not kwargs:
            return self.thyme_text(args[0]) if args else ""
        if name == "range" and 1 <= len(args) <= 3 and not kwargs:
            if any(type(item) is not int for item in args) or (len(args) == 3 and args[2] == 0):
                self.fail("range needs integer arguments")
            values = range(*args)
            if len(values) > THYME_MAX_LOOP_ITEMS: self.fail("range is limited to 32 items")
            return tuple(values)
        if name == "cv2.imwrite" and len(args) == 2 and not kwargs and isinstance(args[1], Frame):
            frame = args[1]
            if not frame.array:
                self.fail("cv2.imwrite needs an ndarray image")
            if not frame.bgr:
                self.allocate(frame, frame.image.size)
                self.allocate(frame, frame.image.size)
                r, g, b = frame.image.split()
                frame = Frame(Image.merge("RGB", (b, g, r)), frame.box)
            else:
                frame = Frame(frame.image, frame.box)
            self.thyme_store(args[0], frame)
            return True
        if name == "cv2.resize" and 1 <= len(args) <= 2 and not set(kwargs)-{"dsize", "fx", "fy", "interpolation"} and (
                "fx" in kwargs or "fy" in kwargs or "dsize" in kwargs or (len(args) == 2 and args[1] is None)):
            frame = args[0]
            if not isinstance(frame, Frame): self.fail("resize requires an image")
            size = args[1] if len(args) == 2 else kwargs.get("dsize")
            if size is None or (isinstance(size, (tuple, list)) and tuple(size) == (0, 0)):
                fx, fy = self.number(kwargs.get("fx", 0)), self.number(kwargs.get("fy", 0))
                if fx <= 0 or fy <= 0: self.fail("cv2.resize needs positive fx/fy without dsize")
                size = (round(frame.image.width * fx), round(frame.image.height * fy))
            return self.call(frame, "resize", [size], {"resample": kwargs.get("interpolation", 2)})
        if name.startswith("ImageEnhance.") and name[len("ImageEnhance."):] in THYME_ENHANCERS and len(args) == 1 and not kwargs:
            return Enhancer(name[len("ImageEnhance."):], self.thyme_pixels(args[0]))
        if name.startswith("ImageOps.") and name[len("ImageOps."):] in THYME_IMAGEOPS and len(args) == 1:
            frame = self.thyme_pixels(args[0])
            function = name[len("ImageOps."):]
            if set(kwargs) - ({"cutoff"} if function == "autocontrast" else set()):
                self.fail("Unsupported ImageOps arguments")
            cutoff = kwargs.get("cutoff", 0)
            if function == "autocontrast" and not 0 <= self.number(cutoff) < 50:
                self.fail("autocontrast cutoff must be within [0, 50)")
            out = self.allocate(frame, frame.image.size)
            image = frame.image if frame.image.mode in ("RGB", "L") else frame.image.convert("RGB")
            result = THYME_IMAGEOPS[function](image, cutoff=cutoff) if function == "autocontrast" else THYME_IMAGEOPS[function](image)
            return Frame(result, out.box)
        return _UNHANDLED


def tool_schema(protocol: str) -> dict[str, Any]:
    require_supported(protocol)
    if protocol in CODE_PROTOCOLS:
        raise UnsupportedOperation("Code protocols do not expose a JSON crop tool")
    if protocol == "pixelreasoner":
        name = "crop_image_normalized"
        description = "Zoom in on the image based on the bounding box coordinates. It is useful when the object or text in the image is too small to be seen."
        properties = {
            "bbox_2d": {"type": "array", "description": "coordinates for bounding box of the area you want to zoom in. minimum value is 0 and maximum value is 1.", "items": {"type": "number"}},
            "target_image": {"type": "number", "description": "The index of the image to crop. Index from 1 to the number of images. Choose 1 to operate on original image."},
        }
        required = ["bbox_2d", "target_image"]
    else:
        name = "image_zoom_in_tool"
        description = "Zoom in on a specific region of an image by cropping it based on a bounding box (bbox) and an optional object label."
        properties = {
            "bbox_2d": {"type": "array", "items": {"type": "number"}, "minItems": 4, "maxItems": 4,
                        "description": "The bounding box of the region to zoom in, as [x1, y1, x2, y2], where (x1, y1) is the top-left corner and (x2, y2) is the bottom-right corner."},
            "label": {"type": "string", "description": "The name or label of the object in the specified bounding box (optional)."},
        }
        # Official prompt has a typo ('bbox'); the executor consumes bbox_2d.
        required = ["bbox_2d"]
    return {"type": "function", "function": {"name": name, "description": description,
            "parameters": {"type": "object", "properties": properties, "required": required}}}


def system_prompt(protocol: str, tools: bool) -> str:
    require_supported(protocol)
    if not tools:
        return "You are a helpful assistant. Answer without calling tools or writing executable code."
    if protocol == "thyme":
        return THYME_SYSTEM
    if protocol == "deepeyesv2":
        return V2_SYSTEM
    schema = json.dumps(tool_schema(protocol), ensure_ascii=False, separators=(",", ":"))
    return (
        "You are a helpful assistant.\n\n# Tools\n"
        "You may call one or more functions to assist with the user query.\n"
        "You are provided with function signatures within <tools></tools> XML tags:\n"
        f"<tools>\n{schema}\n</tools>\n\n"
        "For each function call, return a json object with function name and arguments within <tool_call></tool_call> XML tags:\n"
        '<tool_call>\n{"name": <function-name>, "arguments": <args-json-object>}\n</tool_call>'
    )


def user_prompt(question: str, protocol: str, tools: bool, size: tuple[int, int] | None = None) -> str:
    require_supported(protocol)
    if protocol == "thyme":
        dimensions = f"{size[0]}x{size[1]}" if size else "unknown"
        return (f'<image>\n{question}\n\n### User Image Path:** "{ORIGINAL_ALIAS}"\n'
                f'### User Image Size:** "{dimensions}"\n\n### **Output Format (strict adherence required):**\n\n'
                '<think>Your detailed reasoning process, including any code, should go here.</think>\n'
                "<answer>Your final answer to the user's question goes here.</answer>\n")
    if protocol == "deepeyesv2":
        return "<image>\n" + question + V2_USER_SUFFIX
    if protocol == "pixelreasoner":
        return "<image>\n" + question + PIXEL_SUFFIX
    suffix = DEEPEYES_SUFFIX if tools else "\nThink first, then answer. Format strictly as: <think>...</think> <answer>...</answer> "
    return "<image>\nQuestion: " + question + suffix


def format_call(call: dict[str, Any]) -> str:
    if call.get("name") == "bounded_image_code":
        return "<code>\n```python\n" + call["arguments"]["code"] + "\n```\n</code>"
    return "<tool_call>\n" + json.dumps(call, ensure_ascii=False) + "\n</tool_call>"


def forced_assistant(protocol: str, call: dict[str, Any]) -> str:
    require_supported(protocol)
    if protocol == "deepeyes":
        return "<think>" + DEEPEYES_FORCED_THINK + "</think>  \n" + format_call(call)
    return format_call(call)


def has_operation(text: str) -> bool:
    return bool(re.search(r"<tool_call\b|<code\b|```(?:python|py)\b", text or "", re.I))


def bounded_action(text: str, protocol: str = "pixelreasoner") -> tuple[str, dict[str, Any] | None]:
    code_match, tool_match = CODE_RE.search(text), TOOL_RE.search(text)
    match = min((item for item in (code_match, tool_match) if item), key=lambda item: item.start(), default=None)
    if match is code_match and match is not None:
        if protocol not in CODE_PROTOCOLS:
            raise UnsupportedOperation("Code is not part of this model's native JSON protocol")
        final_markers = [text.find(marker) for marker in ("\\boxed", "<answer>") if marker in text]
        if final_markers and min(final_markers) < match.start():
            return text[:match.start()], None
        code = re.sub(r"^```(?:python|py)?\s*\n?", "", match.group(1).strip(), flags=re.I)
        code = re.sub(r"\s*```$", "", code)
        return text[:match.end()], {"name": "bounded_image_code", "arguments": {"code": code}}
    if tool_match is not None and protocol in CODE_PROTOCOLS:
        raise UnsupportedOperation("JSON tools/search are unsupported in this code protocol")
    if match is None:
        if has_operation(text):
            raise ValueError("Malformed or unclosed tool call")
        return text, None
    final_markers = [text.find(marker) for marker in ("\\boxed", "<answer>") if marker in text]
    if final_markers and min(final_markers) < match.start():
        return text[:match.start()], None
    try:
        call = json.loads(match.group(1))
    except (ValueError, TypeError) as exc:
        raise ValueError("Malformed tool-call JSON") from exc
    if not isinstance(call, dict) or not isinstance(call.get("arguments"), dict):
        raise ValueError("Tool call must have object arguments")
    return text[:match.end()], call


def native_call(protocol: str, image: Image.Image, bbox_1000: list[float]) -> dict[str, Any]:
    require_supported(protocol)
    if protocol == "pixelreasoner":
        values = [min(float(v) / 1000, math.nextafter(1.0, 0.0)) for v in bbox_1000]
        return {"name": "crop_image_normalized", "arguments": {"bbox_2d": values, "target_image": 1}}
    values = [round(float(v) / 1000 * (image.width if i % 2 == 0 else image.height))
              for i, v in enumerate(bbox_1000)]
    if protocol in CODE_PROTOCOLS:
        if protocol == "thyme":
            code = (f"from PIL import Image\nimage = Image.open({ORIGINAL_ALIAS!r})\n"
                    f"cropped_image = image.crop({tuple(values)!r})\n"
                    f"processed_path = {RESULT_ALIAS!r}\ncropped_image.save(processed_path)\nprint(processed_path)")
        else:
            code = ("import matplotlib.pyplot as plt\n"
                    f"cropped_image = image_1.crop({tuple(values)!r})\n"
                    "plt.imshow(cropped_image)\nplt.axis('off')\nplt.show()")
        return {"name": "bounded_image_code", "arguments": {"code": code}}
    return {"name": "image_zoom_in_tool", "arguments": {"bbox_2d": values}}


def execute_native(protocol: str, images: list[Image.Image], call: dict[str, Any]) -> tuple[Image.Image, list[float]]:
    require_supported(protocol)
    if protocol in CODE_PROTOCOLS:
        result = execute_code(protocol, ImageInterpreter(images[0], protocol), call)
        if len(result.frames) != 1:
            raise UnsupportedOperation("Canonical intervention requires exactly one image")
        return result.frames[0].image, list(result.frames[0].box)
    arguments = call.get("arguments")
    if not isinstance(arguments, dict):
        raise ValueError("arguments must be an object")
    if call.get("name") != tool_schema(protocol)["function"]["name"]:
        raise UnsupportedOperation(f"Unsupported image operation: {call.get('name')!r}")
    allowed = {"bbox_2d", "target_image"} if protocol == "pixelreasoner" else {"bbox_2d", "label"}
    if set(arguments) - allowed:
        raise UnsupportedOperation("Unexpected arguments (paths/code are never accepted)")
    values = arguments.get("bbox_2d")
    if not isinstance(values, list) or len(values) != 4 or any(
        type(v) not in (int, float) or not math.isfinite(v) for v in values
    ):
        raise ValueError("bbox_2d must contain four finite numbers")
    target = arguments.get("target_image", 1)
    if type(target) is not int or not 1 <= target <= len(images):
        raise ValueError("target_image must be a valid 1-based integer")
    image = images[target - 1] if protocol == "pixelreasoner" else images[0]
    if protocol == "pixelreasoner":
        normalized = [float(v) for v in values] if all(v < 1 for v in values) else [
            float(v) / (image.width if i % 2 == 0 else image.height) for i, v in enumerate(values)]
        box = [max(0.0, normalized[0] - .1) * image.width,
               max(0.0, normalized[1] - .1) * image.height,
               min(1.0, normalized[2] + .1) * image.width,
               min(1.0, normalized[3] + .1) * image.height]
    else:
        box = [max(0.0, values[0]), max(0.0, values[1]),
               min(float(image.width), values[2]), min(float(image.height), values[3])]
    width, height = box[2] - box[0], box[3] - box[1]
    if min(width, height) <= 0:
        raise ValueError("Native crop must have positive width and height after clipping")
    if protocol == "pixelreasoner" and min(width, height) <= 28:
        raise ValueError("Native crop is too small")
    if box[0] < 0 or box[1] < 0 or box[2] > image.width or box[3] > image.height:
        raise ValueError("Native crop is outside source bounds")
    crop = image.crop(tuple(box)).convert("RGB")
    if min(crop.size) <= 0:
        raise ValueError("Rounded native crop is empty")
    if protocol == "pixelreasoner" and min(crop.size) <= 28:
        raise ValueError("Rounded native crop is too small")
    return crop, box


def execute_code(protocol: str, interpreter: ImageInterpreter, call: dict[str, Any]) -> CodeResult:
    if protocol not in CODE_PROTOCOLS or call.get("name") != "bounded_image_code":
        raise UnsupportedOperation("Unsupported code operation")
    args = call.get("arguments", {})
    if set(args) != {"code"} or type(args["code"]) is not str:
        raise UnsupportedOperation("Code operation requires only a code string")
    return interpreter.run(args["code"])


def literal_text(text: str) -> str:
    for marker in ("<image>", "<video>", "<audio>", "<|", "<img>"):
        text = text.replace(marker, "&lt;" + marker[1:])
    return text


def observation(protocol: str, crop: Image.Image | None, stdout: str = "", error: str = "", count: int = 1) -> str:
    require_supported(protocol)
    stdout, error = literal_text(stdout), literal_text(error)
    if protocol == "thyme":
        payload = "<image>" * count if count else (error or stdout)
        return "<sandbox_output>" + payload + "</sandbox_output>"
    if protocol == "deepeyesv2":
        return f"Code execution result:\nstdout:\n```\n{stdout}\n```\n\nstderr:\n```\n{error}\n```\n\nImages:\n" + "<image>" * count
    if error:
        return "Execution error: " + error
    if protocol == "pixelreasoner":
        return f"\nHere is the cropped image (Image Size: {crop.width}x{crop.height}):\n<image>"
    return "<tool_response><image>" + DEEPEYES_SUFFIX + "</tool_response>"


def append_assistant(request: dict[str, Any], protocol: str, text: str) -> None:
    text = literal_text(text)
    if protocol == "thyme" and request["messages"][-1]["role"] == "assistant":
        request["messages"][-1]["content"] += text
    else:
        request["messages"].append({"role": "assistant", "content": text})


def append_observation(request: dict[str, Any], protocol: str, text: str) -> None:
    if protocol == "thyme":
        request["messages"][-1]["content"] += "\n" + text
    else:
        request["messages"].append({"role": "user", "content": text})


def budget_crop(image: Image.Image, tokens: int = 1960) -> Image.Image:
    if tokens <= 0:
        raise ValueError("crop budget must be positive")
    limit = tokens * 28 ** 2
    if image.width * image.height > limit:
        scale = math.sqrt(limit / (image.width * image.height))
        width = max(1, math.floor(image.width * scale))
        height = max(1, math.floor(image.height * scale))
        if width * height > limit:
            if width >= height:
                width = max(1, limit // height)
            else:
                height = max(1, limit // width)
        image = image.resize((width, height), Image.Resampling.LANCZOS)
    return image


def data_url(image: Image.Image) -> str:
    buffer = io.BytesIO()
    image.convert("RGB").save(buffer, format="JPEG", quality=95)
    return "data:image/jpeg;base64," + base64.b64encode(buffer.getvalue()).decode("ascii")
